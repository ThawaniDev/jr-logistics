/** Stable, machine-readable application errors. Never leak internals. */
export type ErrorCode =
  | "UNAUTHENTICATED" | "FORBIDDEN" | "NOT_FOUND" | "VALIDATION" | "CONFLICT"
  | "INVALID_TRANSITION" | "INSUFFICIENT_FUNDS" | "NO_APPROVED_PRICE" | "SERVICE_DISABLED"
  | "OVERLAPPING_JOB" | "NOT_ELIGIBLE" | "SLOT_TAKEN" | "RATE_LIMITED" | "VERIFICATION_REQUIRED"
  | "TERMS_REQUIRED" | "DISPUTE_BLOCKS" | "NOTHING_TO_DO" | "PASSWORD_CHANGE_REQUIRED" | "MFA_SETUP_REQUIRED" | "DEPENDENCY_UNAVAILABLE"
  | "MANIFEST_REQUIRED" | "OTP_REQUIRED" | "OTP_INVALID" | "OTP_LOCKED" | "STOP_LOCKED" | "STOPS_PENDING" | "RETURNS_PENDING" | "WAIT_REQUIRED" | "PAYLOAD_TOO_LARGE" | "CREDIT_LIMIT_EXCEEDED" | "DETAILS_INCOMPLETE" | "WAREHOUSE_LOCATION_REQUIRED" | "LOCATION_REQUIRED" | "TOO_FAR_FROM_WAREHOUSE" | "EVIDENCE_REQUIRED" | "SIGNATURE_REQUIRED" | "CASH_MISMATCH" | "FEATURE_DISABLED" | "INTERNAL";

const STATUS: Record<ErrorCode, number> = {
  UNAUTHENTICATED: 401, FORBIDDEN: 403, NOT_FOUND: 404, VALIDATION: 422, CONFLICT: 409,
  INVALID_TRANSITION: 409, INSUFFICIENT_FUNDS: 402, NO_APPROVED_PRICE: 422, SERVICE_DISABLED: 422,
  OVERLAPPING_JOB: 409, NOT_ELIGIBLE: 403, SLOT_TAKEN: 409, RATE_LIMITED: 429, VERIFICATION_REQUIRED: 403,
  TERMS_REQUIRED: 422, DISPUTE_BLOCKS: 409, NOTHING_TO_DO: 409, PASSWORD_CHANGE_REQUIRED: 403, MFA_SETUP_REQUIRED: 403, DEPENDENCY_UNAVAILABLE: 503,
  MANIFEST_REQUIRED: 422, OTP_REQUIRED: 422, OTP_INVALID: 422, OTP_LOCKED: 423, STOP_LOCKED: 409, STOPS_PENDING: 409, RETURNS_PENDING: 409, WAIT_REQUIRED: 409, PAYLOAD_TOO_LARGE: 413, CREDIT_LIMIT_EXCEEDED: 402, DETAILS_INCOMPLETE: 422, WAREHOUSE_LOCATION_REQUIRED: 422, LOCATION_REQUIRED: 422, TOO_FAR_FROM_WAREHOUSE: 422, EVIDENCE_REQUIRED: 422, SIGNATURE_REQUIRED: 422, CASH_MISMATCH: 422, FEATURE_DISABLED: 403, INTERNAL: 500,
};

export class AppError extends Error {
  readonly code: ErrorCode;
  readonly status: number;
  readonly details?: Record<string, unknown>;
  constructor(code: ErrorCode, message?: string, details?: Record<string, unknown>) {
    super(message ?? code);
    this.code = code;
    this.status = STATUS[code];
    this.details = details;
  }
}

export const err = (code: ErrorCode, message?: string, details?: Record<string, unknown>) =>
  new AppError(code, message, details);
